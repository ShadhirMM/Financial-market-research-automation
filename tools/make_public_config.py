"""Build config/public-sample.toml from config/config.toml without the series whose owners restrict
redistribution (S&P 500, Dow Jones, Nasdaq, VIX, ICE BofA HY spread) and the checks that use them.

Run: python tools/make_public_config.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
RESTRICTED = {"SP500", "NASDAQCOM", "DJIA", "VIXCLS", "BAMLH0A0HYM2"}
SERIES = "# ---------------------------------------------------------------- series"
CHECKS = "# ---------------------------------------------------------------- research checks"
NOTE = ("# PUBLIC SAMPLE configuration: the same as config.toml, minus series whose owners do not allow\n"
        "# redistribution (S&P 500, Dow Jones, Nasdaq, VIX, ICE BofA HY spread). Used only to build the\n"
        "# committed live sample in docs/sample/ by rebuilding from a live run's raw files.\n"
        "# Generated by tools/make_public_config.py; do not edit by hand.\n\n")


def split(text: str, marker: str) -> tuple[str, list[str]]:
    parts = text.split(marker)
    return parts[0], [marker + p for p in parts[1:]]


def build(src: str) -> str:
    head, rest = src.split(SERIES, 1)
    series_part, checks_part = rest.split(CHECKS, 1)
    pre_s, sblocks = split(series_part, "[[series]]")
    pre_c, cblocks = split(checks_part, "[[checks]]")
    keep_s = [b for b in sblocks if not any(f'id = "{x}"' in b for x in RESTRICTED)]
    keep_c = [b for b in cblocks if not any(f'series = "{x}"' in b for x in RESTRICTED)]
    head = head.replace('reports_dir = "reports"', 'reports_dir = "reports/public-sample"')
    head = head.replace('logs_dir = "logs"', 'logs_dir = "logs/public-sample"')
    return NOTE + head + SERIES + pre_s + "".join(keep_s) + CHECKS + pre_c + "".join(keep_c)


if __name__ == "__main__":
    out = build((ROOT / "config" / "config.toml").read_text(encoding="utf-8"))
    (ROOT / "config" / "public-sample.toml").write_text(out, encoding="utf-8")
    print("wrote config/public-sample.toml")
